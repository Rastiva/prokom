def buat_baju(ukuran="besar", tulisan="Saya suka Python"):
    print(f"Baju berukuran {ukuran} dengan tulisan '{tulisan}'.")

# Baju besar dengan tulisan default
buat_baju()

# Baju sedang dengan tulisan default
buat_baju(ukuran="sedang")

# Baju ukuran kecil dengan tulisan berbeda
buat_baju(ukuran="kecil", tulisan="tetap berjuang!")